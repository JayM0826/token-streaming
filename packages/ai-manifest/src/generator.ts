export async function generateFallbackManifest(
  repoRoot: string,
  summary: RepoSummary,
  options: ScaffoldManifestOptions = {}
): Promise<GeneratedManifestResult> {
  const generatedRoot = path.join(repoRoot, ".ai", "generated");
  await fs.mkdir(generatedRoot, { recursive: true });
  const created: string[] = [];
  const skipped: string[] = [];

  await writeGeneratedFile(
    generatedRoot,
    "project.md",
    [
      "# Generated Project Summary",
      "",
      "This file was generated by Token Streaming because no root `.ai/` manifest was found.",
      "",
      `Repository root: ${summary.root}`,
      `Package manager: ${summary.packageManager ?? "unknown"}`,
      "",
      "Review and promote this content into `.ai/project.md` when it is accurate."
    ].join("\n"),
    options,
    created,
    skipped
  );
  await writeGeneratedFile(
    generatedRoot,
    "architecture.md",
    [
      "# Generated Architecture Notes",
      "",
      "Detected source directories:",
      ...summary.sourceDirectories.map((directory) => `- ${directory}`),
      "",
      "Detected module manifests:",
      ...emptyAwareList(summary.moduleManifestPaths),
      "",
      "Detected workflow manifests:",
      ...emptyAwareList(summary.workflowManifestPaths)
    ].join("\n"),
    options,
    created,
    skipped
  );
  await writeGeneratedFile(generatedRoot, "commands.yaml", stringifySimpleYaml(inferCommandGroups(summary)), options, created, skipped);
  await writeGeneratedFile(
    generatedRoot,
    "tests.yaml",
    stringifySimpleYaml({
      default: inferTestCommands(summary)
    }),
    options,
    created,
    skipped
  );
  await writeGeneratedFile(
    generatedRoot,
    "repo-map.json",
    JSON.stringify(buildGeneratedRepoMap(summary), null, 2),
    options,
    created,
    skipped
  );

  return { root: generatedRoot, files: [...created, ...skipped], created, skipped };
}

