import { promises as fs } from "node:fs";
import path from "node:path";
import type { RepoSummary } from "@token-streaming/protocol";
import { stringifySimpleYaml } from "./simple-yaml.js";

export interface GeneratedManifestResult {
  root: string;
  files: string[];
  created: string[];
  skipped: string[];
}

export interface ScaffoldManifestResult {
  root: string;
  created: string[];
  skipped: string[];
}

export interface ScaffoldManifestOptions {
  overwrite?: boolean;
}

