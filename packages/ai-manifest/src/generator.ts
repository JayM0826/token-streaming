function inferTestCommands(summary: RepoSummary): string[] {
  const scriptCommands = inferTestScriptNames(summary.scripts).map((name) => `${summary.packageManager ?? "pnpm"} run ${name}`);
  const pythonCommands = inferPythonCommandGroups(summary);
  return [
    ...new Set([
      ...scriptCommands,
      ...(summary.verificationCommands ?? []),
      ...(pythonCommands.test ?? []),
      ...(pythonCommands.lint ?? []),
      ...(pythonCommands.typecheck ?? [])
    ])
  ];
}

function inferCommandGroups(summary: RepoSummary): Record<string, string[]> {
  const scriptGroups = Object.fromEntries(
    Object.keys(summary.scripts)
      .sort()
      .map((name) => [name, [`${summary.packageManager ?? "pnpm"} run ${name}`]])
  );
  const pythonGroups = inferPythonCommandGroups(summary);
  const install = inferInstallCommands(summary);
  return { ...(install.length ? { install } : {}), ...pythonGroups, ...scriptGroups };
}

function inferInstallCommands(summary: RepoSummary): string[] {
  if (summary.packageManager) {
    return [`${summary.packageManager} install`];
  }
  const files = new Set(summary.trackedFiles.map((file) => normalizeRepoPath(file).toLowerCase()));
  if (files.has("uv.lock")) {
    return ["uv sync"];
  }
  if (files.has("poetry.lock")) {
    return ["poetry install"];
  }
  if (files.has("requirements.txt")) {
    return ["python -m pip install -r requirements.txt"];
  }
  if (files.has("pyproject.toml") || files.has("setup.py")) {
    return ["python -m pip install -e ."];
  }
  return [];
}

function inferPythonCommandGroups(summary: RepoSummary): Record<string, string[]> {
  if (!isPythonRepository(summary)) {
    return {};
  }
  const files = summary.trackedFiles.map((file) => normalizeRepoPath(file).toLowerCase());
  const groups: Record<string, string[]> = {};
  if (files.some((file) => isTestFile(file)) || files.some((file) => /(^|\/)(pytest\.ini|conftest\.py)$/.test(file))) {
    groups.test = ["python -m pytest"];
  }
  if (files.some((file) => /(^|\/)(ruff\.toml|\.ruff\.toml)$/.test(file))) {
    groups.lint = ["python -m ruff check ."];
  }
  if (files.some((file) => /(^|\/)(mypy\.ini|\.mypy\.ini)$/.test(file))) {
    groups.typecheck = ["python -m mypy ."];
  }
  return groups;
}

function isPythonRepository(summary: RepoSummary): boolean {
  return summary.trackedFiles.some(
    (file) => /\.py$/i.test(file) || /(^|\/)(pyproject\.toml|requirements\.txt|setup\.py)$/i.test(normalizeRepoPath(file))
  );
}

function buildGeneratedRepoMap(summary: RepoSummary): Record<string, unknown> {
  const normalizedFiles = summary.trackedFiles.map(normalizeRepoPath);
  const moduleCandidates = inferModuleCandidates(normalizedFiles);
  const workflowCandidates = inferWorkflowCandidates(normalizedFiles);

  return {
    trackedFiles: summary.trackedFiles,
    sourceDirectories: summary.sourceDirectories,
    moduleManifestPaths: summary.moduleManifestPaths,
    workflowManifestPaths: summary.workflowManifestPaths,
    verificationCommands: summary.verificationCommands ?? [],
    inferredModules: moduleCandidates,
    inferredWorkflows: workflowCandidates,
    testMappings: inferTestMappings(normalizedFiles, moduleCandidates, workflowCandidates),
    notes: [
      "Generated candidates are heuristic mappings for inherited repositories.",
      "Promote accurate candidates into module.yaml or flow.yaml before treating them as authoritative."
    ]
  };
}

interface GeneratedModuleCandidate {
  name: string;
  root: string;
  confidence: "low" | "medium" | "high";
  evidence: string[];
  publicApiCandidates: string[];
  testCandidates: string[];
}

interface GeneratedWorkflowCandidate {
  name: string;
  root: string;
  confidence: "low" | "medium" | "high";
  evidence: string[];
  touches: string[];
  testCandidates: string[];
}

function inferModuleCandidates(files: string[]): GeneratedModuleCandidate[] {
  const groups = new Map<string, string[]>();
  for (const file of files) {
    const root = inferModuleRoot(file);
    if (!root) {
      continue;
    }
    groups.set(root, [...(groups.get(root) ?? []), file]);
  }

  return [...groups.entries()]
    .map(([root, groupFiles]) => {
      const publicApiCandidates = groupFiles.filter(isPublicApiCandidate).slice(0, 5);
      const testCandidates = groupFiles.filter(isTestFile).slice(0, 5);
      const evidence = [
        `${groupFiles.length} file(s) under ${root}`,
        publicApiCandidates.length ? `public API-like files: ${publicApiCandidates.join(", ")}` : undefined,
        testCandidates.length ? `tests: ${testCandidates.join(", ")}` : undefined
      ].filter((value): value is string => typeof value === "string");

      return {
        name: root.split("/").at(-1) ?? root,
        root,
        confidence: confidenceFor(groupFiles.length, publicApiCandidates.length, testCandidates.length),
        evidence,
        publicApiCandidates,
        testCandidates
      };
    })
    .sort((left, right) => scoreConfidence(right.confidence) - scoreConfidence(left.confidence) || left.root.localeCompare(right.root))
    .slice(0, 20);
}

function inferWorkflowCandidates(files: string[]): GeneratedWorkflowCandidate[] {
  const roots = new Map<string, string[]>();
  for (const file of files) {
    const root = inferWorkflowRoot(file);
    if (!root) {
      continue;
    }
    roots.set(root, [...(roots.get(root) ?? []), file]);
  }

  return [...roots.entries()]
    .map(([root, groupFiles]) => {
      const testCandidates = groupFiles.filter(isTestFile).slice(0, 5);
      const touches = inferWorkflowTouches(root, files);
      return {
        name: root.split("/").at(-1) ?? root,
        root,
        confidence: confidenceFor(groupFiles.length, touches.length, testCandidates.length),
        evidence: [
          `${groupFiles.length} workflow/use-case file(s) under ${root}`,
          touches.length ? `nearby module hints: ${touches.join(", ")}` : "no module hints detected",
          testCandidates.length ? `tests: ${testCandidates.join(", ")}` : "no workflow tests detected"
        ],
        touches,
        testCandidates
      };
    })
    .sort((left, right) => scoreConfidence(right.confidence) - scoreConfidence(left.confidence) || left.root.localeCompare(right.root))
    .slice(0, 20);
}

function inferTestMappings(
  files: string[],
  modules: GeneratedModuleCandidate[],
  workflows: GeneratedWorkflowCandidate[]
): Array<{ target: string; tests: string[]; reason: string }> {
  const mappings = [
    ...modules.map((module) => ({
      target: module.root,
      tests: module.testCandidates.length ? module.testCandidates : nearbyTests(files, module.name),
      reason: "Module candidate matched tests by directory or name."
    })),
    ...workflows.map((workflow) => ({
      target: workflow.root,
      tests: workflow.testCandidates.length ? workflow.testCandidates : nearbyTests(files, workflow.name),
      reason: "Workflow candidate matched tests by directory or name."
    }))
  ];
  return mappings.filter((mapping) => mapping.tests.length > 0);
}

function inferModuleRoot(file: string): string | undefined {
  const parts = file.split("/");
  for (const root of ["src/modules", "packages", "apps", "services", "lib"]) {
    const rootParts = root.split("/");
    if (rootParts.every((part, index) => parts[index] === part) && parts.length > rootParts.length + 1) {
      return parts.slice(0, rootParts.length + 1).join("/");
    }
  }
  if (parts[0] === "app" && parts.length > 2) {
    return parts.slice(0, 2).join("/");
  }
  if (parts[0] === "src" && parts.length > 2 && isPythonSourceFile(file)) {
    return parts.slice(0, 2).join("/");
  }
  if (parts[0] === "src" && parts.length > 2 && /api|service|repository|controller|route|schema|provider/i.test(parts.at(-1) ?? "")) {
    return parts.slice(0, 2).join("/");
  }
  return undefined;
}

function inferWorkflowRoot(file: string): string | undefined {
  const parts = file.split("/");
  for (const root of ["src/workflows", "src/use-cases", "src/usecases", "workflows", "use-cases", "features"]) {
    const rootParts = root.split("/");
    if (rootParts.every((part, index) => parts[index] === part) && parts.length > rootParts.length + 1) {
      return parts.slice(0, rootParts.length + 1).join("/");
    }
  }
  if (/workflow|flow|checkout|onboarding|payment|signup/i.test(file) && !isTestFile(file)) {
    return path.posix.dirname(file);
  }
  return undefined;
}

function inferWorkflowTouches(root: string, files: string[]): string[] {
  const tokens = root
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((token) => token.length > 3);
  const moduleRoots = new Set(files.map(inferModuleRoot).filter((value): value is string => typeof value === "string"));
  return [...moduleRoots].filter((moduleRoot) => tokens.some((token) => moduleRoot.toLowerCase().includes(token))).slice(0, 8);
}

function nearbyTests(files: string[], name: string): string[] {
  const normalizedName = name.toLowerCase();
  return files.filter((file) => isTestFile(file) && file.toLowerCase().includes(normalizedName)).slice(0, 5);
}

function isPublicApiCandidate(file: string): boolean {
  return /(^|\/)(index|api|route|routes|controller|schema|service)\.(ts|tsx|js|jsx|mjs|cjs)$/i.test(file)
    || /(^|\/)(__init__|main|train|eval)\.py$/i.test(file);
}

function isTestFile(file: string): boolean {
  return /(^|\/)(__tests__|tests?|specs?)(\/|$)|\.(test|spec)\.(ts|tsx|js|jsx|mjs|cjs)$/i.test(file)
    || /(^|\/)test_[^/]+\.py$/i.test(file)
    || /(^|\/)[^/]+_test\.py$/i.test(file);
}

function isPythonSourceFile(file: string): boolean {
  return /\.py$/i.test(file) && !isTestFile(file);
}

function confidenceFor(fileCount: number, publicOrTouchCount: number, testCount: number): GeneratedModuleCandidate["confidence"] {
  const score = Math.min(3, fileCount / 4) + publicOrTouchCount + testCount;
  if (score >= 4) {
    return "high";
  }
  if (score >= 2) {
    return "medium";
  }
  return "low";
}

function scoreConfidence(confidence: GeneratedModuleCandidate["confidence"]): number {
  return confidence === "high" ? 3 : confidence === "medium" ? 2 : 1;
}

function normalizeRepoPath(file: string): string {
  return file.replace(/\\/g, "/");
}

function inferTestScriptNames(scripts: Record<string, string>): string[] {
  return Object.keys(scripts)
    .filter((name) => /test|check|lint|type/i.test(name) && !isPlaceholderTestScript(scripts[name] ?? ""));
}

function scriptCommand(summary: RepoSummary, script: string): string[] {
  const command = summary.scripts[script];
  if (!command || (script === "test" && isPlaceholderTestScript(command))) {
    return [];
  }
  return [`${summary.packageManager ?? "pnpm"} run ${script}`];
}

function isPlaceholderTestScript(command: string): boolean {
  const normalized = command.toLowerCase().replace(/\s+/g, " ");
  return normalized.includes("no test specified") || normalized.includes("no tests specified") || normalized.includes("no test configured");
}

function emptyAwareList(values: string[]): string[] {
  return values.length > 0 ? values.map((value) => `- ${value}`) : ["- none detected"];
}

async function writeGeneratedFile(
  root: string,
  name: string,
  content: string,
  options: ScaffoldManifestOptions,
  created: string[],
  skipped: string[]
): Promise<void> {
  const fullPath = path.join(root, name);
  if (!options.overwrite && (await exists(fullPath))) {
    skipped.push(fullPath);
    return;
  }
  await fs.writeFile(fullPath, `${content.trimEnd()}\n`, "utf8");
  created.push(fullPath);
}

async function writeOfficialFile(
  root: string,
  name: string,
  content: string,
  options: ScaffoldManifestOptions,
  created: string[],
  skipped: string[]
): Promise<void> {
  const fullPath = path.join(root, name);
  if (!options.overwrite && (await exists(fullPath))) {
    skipped.push(fullPath);
    return;
  }

  await fs.mkdir(path.dirname(fullPath), { recursive: true });
  await fs.writeFile(fullPath, `${content.trimEnd()}\n`, "utf8");
  created.push(fullPath);
}

async function exists(filePath: string): Promise<boolean> {
  try {
    await fs.access(filePath);
    return true;
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      return false;
    }
    throw error;
  }
}
